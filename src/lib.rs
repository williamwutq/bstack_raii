//! # `bstack_raii`
//!
//! A typed, RAII-style ownership, lifetime, and on-disk-layout layer built on
//! top of the mainline `bstack` `alloc` primitives ([`bstack::BStackRange`],
//! [`bstack::BStackSlice`], [`bstack::BStackOwnedSlice`]). It decouples
//! disk-level destruction ([`BStackDrop`]) from Rust's process-scoped `Drop`,
//! providing persistent-storage ownership with C++-style `unique_ptr` /
//! `shared_ptr` / `weak_ptr` conveniences.
//!
//! It is a separate crate (not a `bstack` feature) so that its large, not-yet-stable
//! ABI surface never gates `bstack`'s ABI stability.
//!
//! ## Module map (bottom-up)
//!
//! | Module         | Contents                                                    |
//! |----------------|-------------------------------------------------------------|
//! | [`layout`]     | On-disk primitives: [`EightCC`], [`BlockHeader`] (both Pod). |
//! | [`reference`]  | [`BStackRef`]: typed range wrapper + buffered `OnDisk` read. |
//! | [`teardown`]   | [`BStackDrop`] trait, [`AutoDrop`] RAII guard, [`dealloc_range`]. |
//! | `construct`    | Block creation: allocate, stamp the header, wire refcounts / control blocks — the build-side counterpart to `teardown`. |
//! | [`block`]      | Block-type contracts: [`BStackCast`], [`BStackBlock`], [`BStackWeakable`]. |
//! | [`refcount`]   | Little-endian atomic CAS ops over on-disk `u64` counters.    |
//! | `bulk`         | Sequential fallbacks for [`BStackRaiiAllocator::alloc_many`] / [`free_many`](BStackRaiiAllocator::free_many); bulk allocators override those trait methods. |
//! | [`clone`]      | [`TryClone`] / [`TryCloneIn`]: fallible clone for handles that touch disk. |
//! | [`handle`]     | Without-allocator inner handles: [`OwnedRef`], [`StrongRef`], [`StrongWeakRef`], [`WeakRef`]. |
//! | [`owned`]      | [`BStackOwned`]: the without-allocator, uniquely-owned block handle. |
//! | [`shared`]     | [`BStackRc`] + [`BStackWeak`]: with-allocator shared handles.|
//! | `cast`         | Typed ↔ untyped handle conversion — the runtime behind `bstack_cast!`. |
//! | `vec`          | [`VecDesc`]-backed growable vectors reached through a fixed-size field. |
//! | [`replace`]    | [`ReplaceError`]: the error a generated `replace_<field>` mutator returns. |
//! | [`registry`]   | Process-wide path↔[`FileId`](registry::FileId) registry underlying `Foreign<T>`. |
//! | `foreign`      | [`Foreign<T>`]: a cross-file pointer (file identity + offset).|
//! | `wal`          | Write-ahead log for atomic multi-slice transactions and leak reclamation. |
//! | `stdlib`       | Ergonomic handle/collection types built entirely on the above (e.g. [`BStackHashMap`], [`BStackDeque`], [`BStackCow`]). |
//!
//! ## Conventions fixed by the ABI
//!
//! * All on-disk multi-byte integers (refcounts, offsets) are **little-endian**,
//!   matching `bstack`'s own on-disk format.
//! * Reads are **buffer-based** (`read_into` + `bytemuck::from_bytes`); there is
//!   no zero-copy path without `mmap`.
//! * The whole layer speaks [`std::io::Result`] / [`std::io::Error`], a
//!   consequence of binding allocators to [`bstack::BStackOwnedSliceAllocator`]
//!   (which pins `Error = io::Error` and `Allocated<'a> = BStackOwnedSlice`).
//!
//! ## Status
//!
//! Feature-complete: the runtime primitives, the procedural macros
//! ([`macro@bstack_block`], [`macro@bstack_enum`], [`bstack_move`],
//! [`bstack_cast`]), and the [`stdlib`] collection suite are all implemented and
//! exercised by the test suite. The main open gap is `Foreign<T>` cross-file
//! deep-clone/teardown dispatch, which is still deferred (a `Foreign` field is
//! byte-copied on clone and freed by nobody on teardown regardless of its
//! ownership annotation) — see the [`foreign`] module docs.

